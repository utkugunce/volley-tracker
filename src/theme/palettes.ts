/** Karşılıklı eşleşen (ayna) tonlar. 500 ve 600 canlı dolgu olarak her iki temada aynı kalır. */
const MIRROR: Partial<Record<Shade, Shade>> = {
  "50": "950",
  "100": "900",
  "200": "800",
  "300": "700",
  "400": "600",
  "700": "300",
  "800": "200",
  "900": "100",
  "950": "50",
};

export const SHADES: Shade[] = ["50", "100", "200", "300", "400", "500", "600", "700", "800", "900", "950"];

/** Açık temada bir paletin tonunu hesaplar. */
export function lightShade(name: PaletteName, shade: Shade): string {
  if (name === "slate") return LIGHT_SLATE[shade];
  const palette = PALETTES[name] as Record<string, string>;
  const mirror = MIRROR[shade];
  return palette[mirror ?? shade];
}

export function darkShade(name: PaletteName, shade: Shade): string {
  return (PALETTES[name] as Record<string, string>)[shade];
}

