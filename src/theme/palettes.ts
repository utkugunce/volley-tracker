export type SemanticToken = keyof typeof SEMANTIC_TOKENS;

/** "#RRGGBB" -> "R G B" (Tailwind <alpha-value> ile uyumlu kanal üçlüsü). */
export function hexToChannels(hex: string): string {
  const h = hex.replace("#", "");
  if (!/^[0-9a-fA-F]{6}$/.test(h)) throw new Error(`Geçersiz hex renk: ${hex}`);
  return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16)).join(" ");
}

export const paletteVar = (name: string, shade: string) => `--c-${name}-${shade}`;
export const semanticVar = (token: string) => `--c-${token}`;

/** Tailwind renk tanımı: CSS değişkeni + alfa desteği. */
export const cssColor = (variable: string) => `rgb(var(${variable}) / <alpha-value>)`;

/** theme-vars.css içeriğini üretir (scripts/gen-theme-vars.mjs ve test tarafından kullanılır). */
export function buildThemeVarsCss(): string {
  const dark: string[] = [];
  const light: string[] = [];
  for (const name of Object.keys(PALETTES) as PaletteName[]) {
    for (const shade of SHADES) {
      dark.push(`  ${paletteVar(name, shade)}: ${hexToChannels(darkShade(name, shade))};`);
      light.push(`  ${paletteVar(name, shade)}: ${hexToChannels(lightShade(name, shade))};`);
    }
  }
  for (const [token, [d, l]] of Object.entries(SEMANTIC_TOKENS)) {
    dark.push(`  ${semanticVar(token)}: ${hexToChannels(d)};`);
    light.push(`  ${semanticVar(token)}: ${hexToChannels(l)};`);
  }
  return [
    "/* OTOMATİK ÜRETİLİR: `node scripts/gen-theme-vars.mjs` — elle düzenlemeyin (src/theme/palettes.ts kaynaktır). */",
    ":root {",
    "  color-scheme: dark;",
    ...dark,
    "}",
    "",
    'html[data-theme="light"] {',
    "  color-scheme: light;",
    ...light,
    "}",
    "",
  ].join("\n");
}
